"""Feature entity."""

import warnings
from typing import Any, List, Optional, Tuple

from pyspark.sql import DataFrame
from pyspark.sql.functions import col

from butterfree.constants import DataType
from butterfree.metadata.feature_metadata import FeatureMetadata
from butterfree.transform.transformations import (
    AggregatedTransform,
    CustomTransform,
    SparkFunctionTransform,
    SQLExpressionTransform,
    StackTransform,
    TransformComponent,
)
from butterfree.transform.transformations.h3_transform import H3HashTransform
from butterfree.transform.utils import Window


class Feature:
    """Defines a Feature.

    A Feature is the result of a transformation over one (or more) data columns
    over an input dataframe. Transformations can be as simple as renaming,
    casting types, mathematical expressions or complex functions/models.

    Attributes:
        name: feature name.
            Can be use by the transformation to derive multiple output columns.
        description: brief explanation regarding the feature.
        dtype: data type for the output columns of this feature.
        from_column: original column to build feature.
            Used when there is transformation or the transformation has no
            reference about the column to use for.
        transformation: transformation that will be applied to create this
            feature.

    """

    def __init__(
        self,
        name: str,
        description: str,
        dtype: Optional[DataType] = None,
        from_column: Optional[str] = None,
        transformation: Optional[TransformComponent] = None,
    ) -> None:
        self.name = name
        self.description = description
        self.transformation = transformation
        self.dtype = dtype
        self.from_column = from_column

    @property
    def dtype(self) -> DataType:
        """Attribute dtype getter."""
        return self.__dtype

    @dtype.setter
    def dtype(self, value: DataType) -> None:
        if (
            not (
                isinstance(self.transformation, AggregatedTransform)
                or isinstance(self.transformation, SparkFunctionTransform)
            )
            and value is None
        ):
            raise ValueError(
                "dtype can't be None, except if the transformation is "
                "AggregatedTransform or SparkFunctionTransform"
            )

        if value is not None and not isinstance(value, DataType):
            raise ValueError("dtype must be a DataType.")

        self.__dtype = value

    @property
    def from_column(self) -> Any:
        """Attribute from_column getter."""
        return self.__from_column  # type: ignore

    @from_column.setter
    def from_column(self, value: str) -> None:
        if (
            isinstance(self.transformation, CustomTransform)
            or isinstance(self.transformation, SQLExpressionTransform)
            or isinstance(self.transformation, H3HashTransform)
            or isinstance(self.transformation, StackTransform)
        ) and value is not None:
            raise ValueError(
                f"from_column parameter doesn't need to be declared, "
                f"the column name {value} would be overwritten with "
                f"another name."
            )

        if value is not None and not isinstance(value, str):
            raise ValueError("from_column must be a string.")

        self.__from_column = value

    @property
    def transformation(self) -> TransformComponent:
        """Attribute transformation getter."""
        return self.__transformation

    @transformation.setter
    def transformation(self, value: TransformComponent) -> None:
        self.__transformation = value

        if value is not None:
            self.__transformation.parent = self

    def get_output_columns(self) -> List[str]:
        """Get output columns that will be generated by this feature engineering.

        Returns
            Output columns names.
        """
        if self.transformation is not None:
            return self.transformation.output_columns
        return [self.name]

    def transform(self, dataframe: DataFrame) -> DataFrame:
        """Performs a transformation to the feature pipeline.

        Args:
            dataframe: input dataframe for the transformation.

        Returns:
            Transformed dataframe.
        """
        if self.transformation:
            return self.transformation.transform(dataframe)

        if self.from_column:
            if self.name in dataframe.columns:
                warnings.warn(
                    f"The column name {self.name} "
                    "already exists in the dataframe and "
                    "will be overwritten with another column."
                )

            dataframe = dataframe.withColumn(self.name, col(self.from_column))

        if self.dtype:
            dataframe = dataframe.withColumn(
                self.name, col(self.name).cast(self.dtype.spark)
            )
        return dataframe

    def _build_feature_column_name(
        self,
        base_name: str,
        pivot_value: Optional[Any] = None,
        window: Optional[Window] = None,
    ) -> str:
        """Helper to build the feature column name based on pivot and window."""
        name = base_name
        if pivot_value is not None:
            name = f"{pivot_value}_{name}"
        if window is not None:
            name = f"{name}_{window.get_name()}"
        return name

    def _prepare_metadata_args_for_aggregated_transform(
        self,
        output_columns: List[str],
        pivot_value: Optional[Any],
        window: Optional[Window],
    ) -> List[Tuple[str, str]]:
        """Prepares metadata arguments for AggregatedTransform.

        The `output_columns` (from `self.transformation.output_columns`) contains a list of
        column names. These names are generated by the `AggregatedTransform` instance
        stored in `self.transformation`.
        The `AggregatedTransform` is designed to produce one output column name for each
        aggregation function in its `self.transformation.functions` list.
        Crucially, the order and number of these generated names in `output_columns`
        directly correspond to the functions in `self.transformation.functions`.
        The naming convention for these columns is often `feature_name__function_type`
        (e.g., "user_total_sales__sum").

        Example:
            - Suppose `self.name` (the Feature's name) is "user_sales".
            - And `self.transformation.functions` is a list representing two aggregations,
                say, a sum and an average.
            - Then `output_columns` (i.e., `self.transformation.output_columns`) would
                likely be `["user_sales__sum", "user_sales__avg"]`.

        If `function_index` is 0 (pointing to the sum function):
            `output_columns[function_index]` (i.e., `output_columns[0]`) would be "user_sales__sum".
        If `function_index` is 1 (pointing to the average function):
            `output_columns[function_index]` (i.e., `output_columns[1]`) would be "user_sales__avg".

        Guarantee of safe access for `output_columns[function_index]`:
            The loop `for function_index, ... in enumerate(self.transformation.functions)` means
            `function_index` will take values from `0` to `len(self.transformation.functions) - 1`.
            Because `AggregatedTransform` ensures that `len(output_columns)` is
            equal to `len(self.transformation.functions)`, `function_index` will always be a
            valid index for the `output_columns` list.
        """  # noqa: E501
        items: List[Tuple[str, str]] = []
        for function_index, function_object in enumerate(self.transformation.functions):
            base_name = output_columns[function_index]
            final_name = self._build_feature_column_name(base_name, pivot_value, window)
            dtype_str = function_object.data_type.name
            items.append((final_name, dtype_str))
        return items

    def _prepare_metadata_args_for_spark_function_transform(
        self,
        output_columns: List[str],
    ) -> List[Tuple[str, str]]:
        """Prepares metadata arguments for SparkFunctionTransform.

        Handles two cases for SparkFunctionTransform:
        1. Internal Windows: If `SparkFunctionTransform` has internal windows defined
           (i.e., `self.transformation._windows` is not empty), the `output_columns`
           already contain the fully formed names including window information.
           In this case, `pivot_value` (effectively None) and `window_from_caller` are
           not used for further name modification.
        2. No Internal Windows: If there are no internal windows, each base name from
           `output_columns` (typically `feature_name__function_name`) is combined with
           `window_from_caller` (if provided) to form the final name.
           `pivot_value` is explicitly ignored (treated as None) in the name construction.
        """  # noqa: E501
        items: List[Tuple[str, str]] = []
        transform: SparkFunctionTransform = self.transformation
        functions = transform.functions
        num_functions = len(functions)

        # TODO: This snippet needs a protection since nothing guarantees that
        # the transformation has internal windows.

        # Output columns already include internal window information.
        # Pivot (always None here effectively)
        for column_name_index, column_name in enumerate(output_columns):
            function_index = column_name_index % num_functions
            function_obj = functions[function_index]
            final_name = column_name
            dtype_str = function_obj.data_type.name
            items.append((final_name, dtype_str))

        return items

    def _prepare_metadata_args(
        self,
        output_columns: List[str],
        pivot_value: Optional[Any] = None,
        window: Optional[Window] = None,
    ) -> List[Tuple[str, str]]:
        """Prepares a list of (final_name, dtype_string) for metadata generation.

        For SparkFunctionTransform, the `pivot_value` argument to
        `_prepare_metadata_args` is not used for final name construction
        (either names are pre-built with internal windows, or pivot is
        explicitly None in `_build_feature_column_name`).
        The `window` argument IS used if there are no internal windows.
        """  # noqa: E501

        # Only used by AggregatedFeatureSets
        if isinstance(self.transformation, AggregatedTransform):
            return self._prepare_metadata_args_for_aggregated_transform(
                output_columns, pivot_value, window
            )
        # Only used by FeatureSets
        elif isinstance(self.transformation, SparkFunctionTransform):
            return self._prepare_metadata_args_for_spark_function_transform(
                output_columns
            )
        else:
            return [
                (column_name_base, self.dtype.name)
                for column_name_base in output_columns
            ]

    def build_metadata(
        self,
        pivot_value: Optional[Any] = None,
        window: Optional[Window] = None,
    ) -> List[FeatureMetadata]:
        """Build the metadata for the feature.

        Args:
            pivot_value: Optional pivot value for naming.
            window: Optional window for naming.

        Returns:
            A list of FeatureMetadata objects.
        """
        output_columns = self.get_output_columns()
        prepared_args = self._prepare_metadata_args(output_columns, pivot_value, window)

        metadata_list = [
            FeatureMetadata(
                name=name,
                data_type=dtype_str,
                description=self.description,
                primary_key=False,
            )
            for name, dtype_str in prepared_args
        ]
        return metadata_list
